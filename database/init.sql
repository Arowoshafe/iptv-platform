-- DEV SCHEMA ONLY. This demo has no subscriber auth, commercial billing, or real content.
-- The tables are intentionally unpopulated. Do not store real customer data here yet.
CREATE TABLE IF NOT EXISTS plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT UNIQUE NOT NULL,
    display_name TEXT NOT NULL,
    currency CHAR(3) NOT NULL CHECK (currency IN ('USD','NGN')),
    price_minor BIGINT NOT NULL CHECK (price_minor >= 0),
    is_active BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS subscribers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscriber_id BIGINT NOT NULL REFERENCES subscribers(id),
    plan_id BIGINT NOT NULL REFERENCES plans(id),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','active','expired','canceled')),
    start_at TIMESTAMPTZ,
    end_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS content_rights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_code TEXT NOT NULL,
    territory CHAR(2) NOT NULL CHECK (territory IN ('US','NG')),
    platform TEXT NOT NULL,
    valid_until TIMESTAMPTZ,
    UNIQUE(channel_code, territory, platform)
);
